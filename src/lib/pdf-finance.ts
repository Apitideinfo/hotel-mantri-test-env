// 2. MONTHLY PROFITABILITY PDF
// ────────────────────────────────────────────────────────────────────────────
export interface MonthlyProfitabilityPDFOpts {
  settings: HotelSettings;
  data: MonthlyProfitability;
}

export async function buildMonthlyProfitabilityPDF(opts: MonthlyProfitabilityPDFOpts): Promise<jsPDF> {
  const { settings, data } = opts;
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });

  const [y, m] = data.month_key.split('-');
  const monthName = new Date(parseInt(y, 10), parseInt(m, 10) - 1, 1)
    .toLocaleDateString('en-IN', { month: 'long', year: 'numeric' });

  await drawPageHeader(doc, settings, 'Monthly Profitability', monthName, false);

  let yy = 36;

  // Revenue section
  yy = sectionHead(doc, 'Revenue', yy, false);
  autoTable(doc, {
    startY: yy,
    margin: { left: 14, right: 14 },
    head: [['Revenue Head', 'Amount']],
    body: [
      ['Room Revenue', rs(data.room_revenue)],
      ['F&B Revenue', rs(data.fb_revenue)],
      ['Laundry Revenue', rs(data.laundry_revenue)],
      ['Other Revenue', rs(data.other_revenue)],
    ],
    foot: [['Total Revenue', rs(data.total_revenue)]],
    showFoot: 'lastPage',
    columnStyles: { 0: { cellWidth: 'auto' }, 1: { cellWidth: 50, halign: 'right' } },
    styles: { fontSize: 9, cellPadding: 3, lineColor: C.border, lineWidth: 0.2 },
    headStyles: { fillColor: C.sectionBg, textColor: C.sectionText },
    footStyles: { fillColor: C.footBg, textColor: C.footText, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: C.altRow },
  });
  yy = (doc as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 4;

  // Expense section
  yy = sectionHead(doc, 'Expenses', yy, false);
  autoTable(doc, {
    startY: yy,
    margin: { left: 14, right: 14 },
    head: [['Expense Head', 'Amount']],
    body: [
      ['Salary', rs(data.salary_expense)],
      ...data.expense_by_category.map((c) => [c.category, rs(c.amount)] as [string, string]),
    ],
    foot: [['Total Expenses', rs(data.total_expenses)]],
    showFoot: 'lastPage',
    columnStyles: { 0: { cellWidth: 'auto' }, 1: { cellWidth: 50, halign: 'right' } },
    styles: { fontSize: 9, cellPadding: 3, lineColor: C.border, lineWidth: 0.2 },
    headStyles: { fillColor: C.sectionBg, textColor: C.sectionText },
    footStyles: { fillColor: C.footBg, textColor: C.footText, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: C.altRow },
  });
  yy = (doc as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 4;

  // Cash Summary section — matches WhatsApp report
  yy = sectionHead(doc, 'Cash Summary', yy, false);
  autoTable(doc, {
    startY: yy,
    margin: { left: 14, right: 14 },
    head: [['Cash Head', 'Amount']],
    body: [
      ['Cash', rs(data.cash)],
      ['Bank', rs(data.bank)],
      ['Salary Advance', rs(data.salary_advance)],
      ['Cash Handover MD Sir', rs(data.cash_handover_md)],
      ['Bank Cash Deposit', rs(data.bank_cash_deposit)],
      ['Cash Closing', rs(data.cash_closing)],
    ],
    columnStyles: { 0: { cellWidth: 'auto' }, 1: { cellWidth: 50, halign: 'right' } },
    styles: { fontSize: 9, cellPadding: 3, lineColor: C.border, lineWidth: 0.2 },
    headStyles: { fillColor: C.sectionBg, textColor: C.sectionText },
    alternateRowStyles: { fillColor: C.altRow },
    theme: 'grid',
    didParseCell(d) {
      if (d.row.index === 5) { // Cash Closing row
        d.cell.styles.fillColor = C.footBg;
        d.cell.styles.fontStyle = 'bold';
        d.cell.styles.textColor = C.footText;
      }
    },
  });
  yy = (doc as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 4;

  // Result section
  yy = sectionHead(doc, 'Result', yy, false);
  const margin = data.profit_margin.toFixed(1);
  autoTable(doc, {
    startY: yy,
    margin: { left: 14, right: 14 },
    head: [],
    body: [
      ['Total Revenue', rs(data.total_revenue)],
      ['Total Expenses', rs(data.total_expenses)],
      ['Net Operating Profit', rs(data.net_operating_profit)],
      ['Profit Margin', `${margin} %`],
    ],
    columnStyles: {
      0: { cellWidth: 120, fontStyle: 'normal', textColor: C.muted, fontSize: 10 },
      1: { fontStyle: 'bold', textColor: C.text, fontSize: 10, halign: 'right' },
    },
    styles: { cellPadding: 4, lineColor: C.border, lineWidth: 0.2 },
    theme: 'plain',
    didParseCell(d) {
      if (typeof d.cell.raw === 'string' && /Net Operating|Profit Margin/.test(d.cell.raw as string)) {
        d.cell.styles.fillColor = C.footBg;
        d.cell.styles.fontStyle = 'bold';
        d.cell.styles.textColor = C.footText;
      }
    },
  });

  addPageFooters(doc, false);
  return doc;
}
