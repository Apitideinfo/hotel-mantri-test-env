// 1. EXPENSE LEDGER PDF
// ────────────────────────────────────────────────────────────────────────────
export interface ExpenseLedgerPDFOpts {
  settings: HotelSettings;
  entries: ExpenseEntry[];
  fromDate: string;
  toDate: string;
}

export async function buildExpenseLedgerPDF(opts: ExpenseLedgerPDFOpts): Promise<jsPDF> {
  const { settings, entries, fromDate, toDate } = opts;
  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' });

  await drawPageHeader(doc, settings, 'Expense Ledger', `${fmtDate(fromDate)} to ${fmtDate(toDate)}`, true);

  let total = 0, cash = 0, bank = 0, upi = 0, credit = 0;
  const catMap = new Map<string, number>();
  for (const e of entries) {
    const amt = toNum(e.amount);
    total += amt;
    if (e.payment_mode === 'Cash') cash += amt;
    else if (e.payment_mode === 'Bank') bank += amt;
    else if (e.payment_mode === 'UPI') upi += amt;
    else if (e.payment_mode === 'Credit') credit += amt;
    catMap.set(e.category_name, (catMap.get(e.category_name) ?? 0) + amt);
  }

  autoTable(doc, {
    startY: 36,
    margin: { left: 10, right: 10 },
    head: [['Date', 'Expense Head', 'Description', 'Bill No.', 'Payment Mode', 'Amount']],
    body: entries.map((e) => [
      fmtDate(e.entry_date),
      String(e.category_name || '—'),
      String(e.description || '—'),
      String(e.bill_no || '—'),
      String(e.payment_mode || '—') + (e.is_paid ? '' : ' (Unpaid)'),
      rs(toNum(e.amount)),
    ]),
    foot: [[
      `Total: ${rs(total)}`, '', '', '', '',
      `Cash: ${rs(cash)}  Bank: ${rs(bank)}  UPI: ${rs(upi)}  Credit: ${rs(credit)}`,
    ]],
    showFoot: 'lastPage',
    theme: 'grid',
    columnStyles: {
      0: { cellWidth: 22, overflow: 'linebreak' },
      1: { cellWidth: 38, overflow: 'linebreak' },
      2: { cellWidth: 'auto', overflow: 'linebreak' },
      3: { cellWidth: 26, overflow: 'linebreak' },
      4: { cellWidth: 30, overflow: 'linebreak' },
      5: { cellWidth: 30, halign: 'right', overflow: 'linebreak' },
    },
    styles: { fontSize: 8, cellPadding: 2.5, lineColor: C.border, lineWidth: 0.2, textColor: C.text, overflow: 'linebreak' },
    headStyles: { fillColor: C.sectionBg, textColor: C.sectionText, fontSize: 8.5, fontStyle: 'bold' },
    footStyles: { fillColor: C.footBg, textColor: C.footText, fontStyle: 'bold', fontSize: 8 },
    alternateRowStyles: { fillColor: C.altRow },
  });

  // Category summary on new page
  doc.addPage();
  let y = 36;
  y = sectionHead(doc, 'Category Summary', y, true);
  autoTable(doc, {
    startY: y,
    margin: { left: 10, right: 10 },
    head: [['Expense Head', 'Amount']],
    body: Array.from(catMap.entries()).sort((a, b) => b[1] - a[1]).map(([cat, amt]) => [String(cat), rs(amt)]),
    foot: [['Total', rs(total)]],
    showFoot: 'lastPage',
    theme: 'grid',
    columnStyles: { 0: { cellWidth: 'auto', overflow: 'linebreak' }, 1: { cellWidth: 50, halign: 'right', overflow: 'linebreak' } },
    styles: { fontSize: 9, cellPadding: 3, lineColor: C.border, lineWidth: 0.2, textColor: C.text, overflow: 'linebreak' },
    headStyles: { fillColor: C.sectionBg, textColor: C.sectionText, fontStyle: 'bold' },
    footStyles: { fillColor: C.footBg, textColor: C.footText, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: C.altRow },
  });

  addPageFooters(doc, true);
  return doc;
}

